#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""控制台登录（SEC-G01）凭据生成器：盐 + sha256(盐 || 口令)。

为什么要自己算
--------------
板子上落的是 16 字节盐和 sha256(salt || password) 的 32 字节摘要，不是口令。
两边必须逐位一致，否则症状是「口令明明对，登录却说不」——一种只在板子上
才看得见的静默错答案。所以这里与内核走同一条式子：
`arkrtos_shell_auth.c` 里 `sha256(salt[16] || argv[1])`，Python 侧 `hashlib`。
门禁 `tools/shell_auth_gate.py` 会用同一段式子对照仓库里那份演示凭据。

用法
----
生成一对新的（盐随机、口令从命令行给）：

    python tools/shell_auth_cred.py --password 'my pass phrase'

只验证已有的盐/摘要（不给口令就只打印摘要，便于和固件对照）：

    python tools/shell_auth_cred.py --salt 61726b2d... --password 'x' --check <hex digest>

输出两种形态：
  * 默认：C 头文件正文（可直接存成 arkrtos_shell_auth_local.h）；
  * `--make`：一行 `printf` 转义，方便贴进 Makefile 的凭据规则。

诚实边界：口令仍然走串口明文（板子没有可信显示），摘要也在固件里（泄露的
镜像可以被离线爆破弱口令）。这一层管的是「串口前的人是不是运维」，不是设备
身份（SEC-G03/SEC-G13）。
"""

import argparse
import hashlib
import os
import sys

SALT_LEN = 16
DIGEST_LEN = 32


def digest_of(salt: bytes, password: bytes) -> bytes:
    return hashlib.sha256(salt + password).digest()


def c_initialiser(data: bytes) -> str:
    return "{ " + ", ".join("0x%02X" % b for b in data) + " }"


def header_text(salt: bytes, digest: bytes, note: str) -> str:
    return (
        "#ifndef ARKRTOS_SHELL_AUTH_LOCAL_H\n"
        "#define ARKRTOS_SHELL_AUTH_LOCAL_H\n"
        "/* %s */\n"
        "#define ARKRTOS_SHELL_AUTH_SALT %s\n"
        "#define ARKRTOS_SHELL_AUTH_DIGEST %s\n"
        "#endif\n" % (note, c_initialiser(salt), c_initialiser(digest))
    )


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Generate Ark RTOS console login credentials")
    ap.add_argument("--password", help="password (required unless --check with --salt)")
    ap.add_argument("--salt", help="16 byte salt as hex (default: random)")
    ap.add_argument("--check", help="32 byte digest as hex: verify instead of print")
    ap.add_argument("--make", action="store_true", help="emit one Makefile printf line")
    ap.add_argument("--note", default="generated by tools/shell_auth_cred.py", help="comment text")
    args = ap.parse_args(argv)

    if args.salt:
        try:
            salt = bytes.fromhex(args.salt)
        except ValueError:
            print("shell_auth_cred: --salt must be hex", file=sys.stderr)
            return 2
        if len(salt) != SALT_LEN:
            print("shell_auth_cred: --salt must be %d bytes, got %d" % (SALT_LEN, len(salt)),
                  file=sys.stderr)
            return 2
    else:
        salt = os.urandom(SALT_LEN)

    if not args.password:
        print("shell_auth_cred: --password is required", file=sys.stderr)
        return 2

    digest = digest_of(salt, args.password.encode("utf-8"))

    if args.check:
        try:
            want = bytes.fromhex(args.check)
        except ValueError:
            print("shell_auth_cred: --check must be hex", file=sys.stderr)
            return 2
        if want == digest:
            print("shell_auth_cred: match (sha256(salt||password) = %s)" % digest.hex())
            return 0
        print("shell_auth_cred: MISMATCH\n  want %s\n  got  %s" % (want.hex(), digest.hex()),
              file=sys.stderr)
        return 1

    if args.make:
        text = header_text(salt, digest, args.note)
        escaped = (text.replace("\\", "\\\\").replace("'", "'\\''")
                       .replace("\n", "\\n"))
        print("printf '%s' > $@" % escaped)
        return 0

    sys.stdout.write(header_text(salt, digest, args.note))
    sys.stdout.write("/* salt hex: %s */\n" % salt.hex())
    return 0


if __name__ == "__main__":
    sys.exit(main())
