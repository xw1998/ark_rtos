#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate kernelsrc/include/arkrtos_autoconf.h from Kconfig + a defconfig.

Every Kconfig symbol is named exactly like the C macro it produces, so the
generated header is a plain list of #defines with no translation layer.

Modes
-----
    --defconfig FILE      resolve defaults, then apply FILE, write --out
    --config FILE         use FILE (a .config) instead of a defconfig
    --olddefconfig FILE   like --config but writes back the filled FILE
    --savedefconfig FILE  write a defconfig of the current values
    --list                print every symbol, type and resolved value
    --check               fail (exit 1) if --out does not match the generator

The generator is deliberately boring: bool becomes 1/0 (never left undefined),
int/hex a parenthesised constant, string a quoted literal.  Emitting 0 for a
disabled bool is intentional - it lets a Kconfig "n" override a header default
of 1, which a missing #define could not do.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kconfig as kc  # noqa: E402


BANNER = """\
/* Auto-generated by tools/kconfig/genconfig.py - DO NOT EDIT.
 *
 * Source of truth:
 *   symbols : Kconfig (+ kconfig/Kconfig.*), the documented menu
 *   values  : {source}
 *
 * Regenerate with:
 *   py -3 tools/kconfig/genconfig.py --defconfig config/arkrtos_defconfig \\
 *       --out kernelsrc/include/arkrtos_autoconf.h
 *
 * Every symbol here is named exactly like the macro it defines.  A disabled
 * bool is written as 0, not omitted, so that a Kconfig "n" can override the
 * #ifndef default in arkrtos_features.h / arkrtos_config.h.
 *
 * Each define is wrapped in #ifndef on purpose: a project that passes
 * -DARKRTOS_USE_LWIP=1 on the compiler command line keeps its value, because
 * the command line is emitted before this header is included.  Kconfig fills
 * the defaults; the project still owns per-target overrides.
 */
"""


def render(kconf, values, source):
    lines = [BANNER.format(source=source), "", "#ifndef ARKRTOS_AUTOCONF_H",
             "#define ARKRTOS_AUTOCONF_H", ""]
    for name in sorted(values):
        s = kconf.symbols.get(name)
        typ = (s.type if s else None) or kc.BOOL
        val = values[name]
        if typ == kc.BOOL:
            body = "#define %s %s" % (name, "1" if val not in ("n", "", "0") else "0")
        elif typ == kc.STRING:
            body = '#define %s "%s"' % (name, val)
        else:  # int / hex
            body = "#define %s (%s)" % (name, val if val != "" else "0")
        lines.append("#ifndef %s" % name)
        lines.append(body)
        lines.append("#endif")
    lines.append("")
    lines.append("#endif /* ARKRTOS_AUTOCONF_H */")
    lines.append("")
    return "\n".join(lines)


def render_defconfig(kconf, values):
    out = ["# Generated by tools/kconfig/genconfig.py --savedefconfig",
           "# Format: NAME=value, one per line. Reapply with --defconfig.", ""]
    for name in sorted(values):
        s = kconf.symbols.get(name)
        if s is not None and not s.visible:
            continue
        out.append("%s=%s" % (name, values[name]))
    out.append("")
    return "\n".join(out)


def build_values(kconf, config_path):
    cfg = kc.Config(kconf)
    cfg.user = kc.parse_config(config_path)
    cfg.resolve()
    return cfg.values


def main(argv):
    ap = argparse.ArgumentParser(description="Ark RTOS Kconfig -> autoconf.h")
    ap.add_argument("--kconfig", default="Kconfig")
    ap.add_argument("--defconfig")
    ap.add_argument("--config")
    ap.add_argument("--olddefconfig")
    ap.add_argument("--savedefconfig")
    ap.add_argument("--out")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args(argv)

    if not os.path.exists(args.kconfig):
        print("genconfig: Kconfig not found: %s" % args.kconfig, file=sys.stderr)
        return 2
    kconf = kc.load(args.kconfig)

    src = None
    path = args.config or args.defconfig or args.olddefconfig
    if path:
        src = os.path.relpath(path).replace("\\", "/")
    values = build_values(kconf, path)

    if args.list:
        for name in sorted(values):
            s = kconf.symbols.get(name)
            print("%-38s %-7s %s" % (name, (s.type if s else "?"), values[name]))
        return 0

    if args.savedefconfig:
        with open(args.savedefconfig, "w", encoding="utf-8", newline="\n") as f:
            f.write(render_defconfig(kconf, values))
        print("savedefconfig -> %s" % args.savedefconfig)
        return 0

    if args.olddefconfig:
        with open(args.olddefconfig, "w", encoding="utf-8", newline="\n") as f:
            f.write(render_defconfig(kconf, values))
        return 0

    if not args.out:
        ap.error("--out is required unless --list/--savedefconfig is used")

    text = render(kconf, values, src or "(built-in defaults)")

    if args.check:
        old = ""
        if os.path.exists(args.out):
            with open(args.out, "r", encoding="utf-8") as f:
                old = f.read()
        if old == text:
            print("kconfig: %s is up to date" % args.out)
            return 0
        print("kconfig: %s is STALE - regenerate it" % args.out, file=sys.stderr)
        return 1

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("genconfig: %s (%d symbols)" % (args.out, len(values)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
